#!/usr/bin/env node
// Generates the app icon set in frontend/public/ from one geometry definition.
// Run from frontend/: `node scripts/gen-icons.mjs`. Outputs are committed.
//
// No dependencies: the mark is only rounded rectangles, one circle and a linear
// gradient, so this file writes the SVGs and rasterises the same shapes itself
// (supersampled coverage) into PNG / ICO with node:zlib.
//
// Design (plan 1b §L): "rising bars" on a 16-px grid. On the 512 canvas one
// pixel at 16 px is 32 units, so the bars are exactly 2 px wide with 2 px gaps
// at 16 px and 4 px at 32 px.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { deflateSync } from "node:zlib";

const VIEW = 512;
const TILE_RADIUS = 96;
const GRADIENT = ["#4f46e5", "#0891b2"]; // indigo-600 -> cyan-600 (white keeps >= 3:1)
const BARS = [
  { x: 96, y: 288, w: 64, h: 128 },
  { x: 224, y: 192, w: 64, h: 224 },
  { x: 352, y: 96, w: 64, h: 320 },
];
const BAR_RADIUS = 16;
const DOT = { cx: 384, cy: 64, r: 24 }; // only in >= 64 px renders
const MASKABLE_SCALE = 0.7; // keeps the glyph inside the 40 % safe-zone circle

/**
 * Variants:
 * - favicon: rounded tile, bars, no dot (tabs, favicon.ico)
 * - any: rounded tile, bars + dot (PWA "any" icons)
 * - maskable: full-bleed square, glyph at 0.7 + dot (PWA maskable, apple-touch)
 * - monochrome: bars only, black on transparent (Safari pinned tab / monochrome)
 */
export const VARIANTS = {
  favicon: { tile: "rounded", dot: false, scale: 1 },
  any: { tile: "rounded", dot: true, scale: 1 },
  maskable: { tile: "square", dot: true, scale: MASKABLE_SCALE },
  monochrome: { tile: "none", dot: false, scale: 1 },
};

// ---------------------------------------------------------------- SVG output

export function svg(variantName) {
  const v = VARIANTS[variantName];
  const mono = v.tile === "none";
  const fill = mono ? "#000" : "#fff";
  const parts = [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${VIEW} ${VIEW}" role="img" aria-label="Investment Overview">`,
    "  <!-- Generated by frontend/scripts/gen-icons.mjs; edit the script, not this file. -->",
  ];
  if (!mono) {
    parts.push(
      "  <defs>",
      '    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">',
      `      <stop offset="0" stop-color="${GRADIENT[0]}"/>`,
      `      <stop offset="1" stop-color="${GRADIENT[1]}"/>`,
      "    </linearGradient>",
      "  </defs>",
      v.tile === "rounded"
        ? `  <rect width="${VIEW}" height="${VIEW}" rx="${TILE_RADIUS}" fill="url(#g)"/>`
        : `  <rect width="${VIEW}" height="${VIEW}" fill="url(#g)"/>`,
    );
  }
  const glyph = BARS.map(
    (b) => `<rect x="${b.x}" y="${b.y}" width="${b.w}" height="${b.h}" rx="${BAR_RADIUS}" fill="${fill}"/>`,
  );
  if (v.dot) glyph.push(`<circle cx="${DOT.cx}" cy="${DOT.cy}" r="${DOT.r}" fill="${fill}"/>`);
  if (v.scale !== 1) {
    const c = VIEW / 2;
    parts.push(`  <g transform="translate(${c} ${c}) scale(${v.scale}) translate(-${c} -${c})">`);
    parts.push(...glyph.map((s) => `    ${s}`), "  </g>");
  } else {
    parts.push(...glyph.map((s) => `  ${s}`));
  }
  parts.push("</svg>", "");
  return parts.join("\n");
}

// ------------------------------------------------------------- rasteriser

function inRoundRect(px, py, x, y, w, h, r) {
  if (px < x || py < y || px > x + w || py > y + h) return false;
  const cx = Math.min(Math.max(px, x + r), x + w - r);
  const cy = Math.min(Math.max(py, y + r), y + h - r);
  const dx = px - cx;
  const dy = py - cy;
  return dx * dx + dy * dy <= r * r;
}

function hex(c) {
  return [1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16));
}

/** Renders a variant to straight-alpha RGBA bytes (size x size). */
export function render(variantName, size) {
  const v = VARIANTS[variantName];
  const ss = size <= 48 ? 16 : size <= 192 ? 8 : 4;
  const k = VIEW / size;
  const c = VIEW / 2;
  const [g0, g1] = GRADIENT.map(hex);
  const out = new Uint8Array(size * size * 4);
  const inGlyph = (ux, uy) => {
    // inverse of the scale-about-centre transform
    const gx = (ux - c) / v.scale + c;
    const gy = (uy - c) / v.scale + c;
    for (const b of BARS) if (inRoundRect(gx, gy, b.x, b.y, b.w, b.h, BAR_RADIUS)) return true;
    if (v.dot) {
      const dx = gx - DOT.cx;
      const dy = gy - DOT.cy;
      if (dx * dx + dy * dy <= DOT.r * DOT.r) return true;
    }
    return false;
  };
  const inTile = (ux, uy) =>
    v.tile === "square" ? true : v.tile === "rounded" ? inRoundRect(ux, uy, 0, 0, VIEW, VIEW, TILE_RADIUS) : false;

  for (let py = 0; py < size; py++) {
    for (let px = 0; px < size; px++) {
      let tile = 0;
      let glyph = 0;
      for (let j = 0; j < ss; j++) {
        for (let i = 0; i < ss; i++) {
          const ux = (px + (i + 0.5) / ss) * k;
          const uy = (py + (j + 0.5) / ss) * k;
          if (inTile(ux, uy)) tile++;
          if (inGlyph(ux, uy)) glyph++;
        }
      }
      const n = ss * ss;
      const o = (py * size + px) * 4;
      if (v.tile === "none") {
        out[o + 3] = Math.round((glyph / n) * 255);
        continue;
      }
      // objectBoundingBox gradient from (0,0) to (1,1) on a square
      const t = (px + 0.5 + py + 0.5) / (2 * size);
      const mix = tile === 0 ? 0 : glyph / tile;
      for (let ch = 0; ch < 3; ch++) {
        const base = g0[ch] + (g1[ch] - g0[ch]) * t;
        out[o + ch] = Math.round(base + (255 - base) * mix);
      }
      out[o + 3] = Math.round((tile / n) * 255);
    }
  }
  return out;
}

// ------------------------------------------------------------ PNG / ICO

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});

function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}

/** Encodes RGBA bytes as an 8-bit RGBA PNG. */
export function encodePng(rgba, width, height = width) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  const stride = width * 4;
  const raw = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (stride + 1)] = 0; // filter: none
    Buffer.from(rgba.buffer, rgba.byteOffset + y * stride, stride).copy(raw, y * (stride + 1) + 1);
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

/** Packs PNG images into one ICO (PNG-in-ICO, supported by every current browser). */
export function encodeIco(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(images.length, 4);
  let offset = 6 + 16 * images.length;
  const entries = images.map(({ size, png }) => {
    const e = Buffer.alloc(16);
    e[0] = size >= 256 ? 0 : size;
    e[1] = size >= 256 ? 0 : size;
    e.writeUInt16LE(1, 4); // planes
    e.writeUInt16LE(32, 6); // bits per pixel
    e.writeUInt32LE(png.length, 8);
    e.writeUInt32LE(offset, 12);
    offset += png.length;
    return e;
  });
  return Buffer.concat([header, ...entries, ...images.map((i) => i.png)]);
}

// ------------------------------------------------------------------ main

function main() {
  const pub = join(dirname(fileURLToPath(import.meta.url)), "..", "public");
  const write = (name, data) => {
    writeFileSync(join(pub, name), data);
    console.log(`wrote public/${name}`);
  };
  const png = (variant, size) => encodePng(render(variant, size), size);

  write("favicon.svg", svg("favicon"));
  write("icon.svg", svg("favicon")); // alias kept for old links and SW caches
  write("icon-maskable.svg", svg("maskable"));
  write("icon-monochrome.svg", svg("monochrome"));
  write("favicon.ico", encodeIco([16, 32, 48].map((size) => ({ size, png: png("favicon", size) }))));
  write("apple-touch-icon.png", png("maskable", 180)); // iOS rounds it itself; no transparency
  write("icon-192.png", png("any", 192));
  write("icon-512.png", png("any", 512));
  write("icon-maskable-192.png", png("maskable", 192));
  write("icon-maskable-512.png", png("maskable", 512));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
